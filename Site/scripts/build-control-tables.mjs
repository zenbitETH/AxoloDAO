#!/usr/bin/env node
/**
 * build-control-tables.mjs
 *
 * Reads YAML files in src/content/{members,partners,projects,species}/ and writes
 * markdown tables to docs/data-tables/. These tables are the build-time control
 * dashboard — humans read them, builds don't depend on them.
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as yamlParse } from 'yaml';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const CONTENT = resolve(ROOT, 'src/content');
const OUT = resolve(ROOT, 'docs/data-tables');
mkdirSync(OUT, { recursive: true });

function loadYAMLs(folder) {
  const dir = join(CONTENT, folder);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.yaml') || f.endsWith('.yml'))
    .map((f) => yamlParse(readFileSync(join(dir, f), 'utf8')));
}

function table(headers, rows) {
  const head = `| ${headers.join(' | ')} |`;
  const sep = `| ${headers.map(() => '---').join(' | ')} |`;
  const body = rows.map((r) => `| ${r.map((c) => String(c ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')).join(' | ')} |`).join('\n');
  return [head, sep, body].join('\n');
}

// --- Members ---------------------------------------------------------------
const members = loadYAMLs('members');
const membersMd = `# Members — control table\n\nGenerated by \`scripts/build-control-tables.mjs\`. Do not edit by hand; edit the YAMLs in \`src/content/members/\`.\n\n` +
  table(
    ['slug', 'name', 'role (es)', 'ENS', 'logo', 'socials'],
    members.map((m) => [m.slug, m.name, m.role?.es, m.ens ?? '—', m.logo ?? '—', (m.socials ?? []).map((s) => `${s.platform}:${s.handle ?? s.url}`).join('; ')])
  );
writeFileSync(join(OUT, 'members.md'), membersMd);

// --- Partners --------------------------------------------------------------
const partners = loadYAMLs('partners');
const partnersMd = `# Partners — control table\n\nGenerated. Edit \`src/content/partners/*.yaml\`.\n\n` +
  table(
    ['slug', 'name', 'featured', 'role (es)', 'logo', 'website'],
    partners.map((p) => [p.slug, p.name, p.featured ? 'YES' : '', p.role?.es, p.logo ?? '—', p.website ?? '—'])
  );
writeFileSync(join(OUT, 'partners.md'), partnersMd);

// --- Projects --------------------------------------------------------------
const projects = loadYAMLs('projects');
const projectsMd = `# Projects — control table\n\nGenerated. Edit \`src/content/projects/*.yaml\`.\n\n` +
  table(
    ['slug', 'name', 'status', 'blurb (es)', 'url'],
    projects.map((p) => [p.slug, p.name, p.status, p.blurb?.es, p.url ?? '—'])
  );
writeFileSync(join(OUT, 'projects.md'), projectsMd);

// --- Species ---------------------------------------------------------------
const species = loadYAMLs('species');
const speciesMd = `# Species — control table\n\nGenerated by \`scripts/build-control-tables.mjs\` from \`scripts/extract-species.mjs\` output.\n\n` +
  table(
    ['slug', 'scientific', 'IUCN', 'NOM-059', 'states', 'common names', 'hero card', 'accent'],
    species.map((s) => [
      s.slug,
      s.scientificName,
      s.iucn ?? '?',
      s.nom059 ?? '—',
      (s.states ?? []).join(', '),
      (s.commonNames ?? []).slice(0, 2).join(', '),
      s.heroCardSvg ? '✓' : '',
      s.accentColor ?? '—',
    ])
  );
writeFileSync(join(OUT, 'species.md'), speciesMd);

console.log(`[tables] wrote 4 control tables to ${OUT}`);
