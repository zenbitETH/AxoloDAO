// The built site carries nothing internal: no path of a private repository, no name of a working session or persona, no package id of the
// internal replay, no review marker. Every text file of the dist is read. The pilot's public chain file names a row's caveat
// `aclaracion` (lib/pilotoPublico.mjs): a `nota` key anywhere in it is the internal file leaking through. And the bytes of EVERY file, images
// and fonts included, carry no local path, private repository, booth database or image generator record (lib/barridoBinario.mjs).
//   node scripts/test-dist-interno.mjs [--dist <dir>]   (after the build)
import { mkdtempSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { problemasDeLaCopiaPublica } from './lib/construccionSitio.mjs';
import { hallazgosBinarios, JPEG_PLANTADO } from './lib/barridoBinario.mjs';
import { cadenaPublica, clipsPublicos, fichaPublica } from '../src/lib/pilotoPublico.mjs';
import { CADENA as CADENA_PRUEBA, CLIPS, FICHA } from './fixtures/piloto-de-prueba.mjs';

const SITE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TEXTO = new Set(['.html', '.js', '.mjs', '.css', '.json', '.geojson', '.txt', '.xml', '.svg', '.webmanifest', '.csv']);
/** What must not be in a served file, with the reason a reader sees. */
export const PROHIBIDO = [
  [/brain-hub-datos|axolodao-brain|brain-plan-innovafest|brain-gtm|context\/datos\/|context\/plans\//, 'a path of a private repository'],
  [/\bLucia\b|\bmaggia\b|\bMaggIA\b|\bBuilder\b|\bGrumpy\b/i, 'the name of a working session or persona'],
  [/semilla-/, 'a package id of the internal replay'],
  [/AUDIT READY/, 'a review marker'],
];

/** The findings in a dist folder, as «file: reason». */
export function hallazgos(dist) {
  const out = [];
  const anda = (d) => {
    for (const n of readdirSync(d)) {
      const f = join(d, n);
      if (statSync(f).isDirectory()) { anda(f); continue; }
      if (!TEXTO.has(extname(n).toLowerCase())) continue;
      const t = readFileSync(f, 'utf8');
      for (const [re, porque] of PROHIBIDO) if (re.test(t)) out.push(`${f.slice(dist.length + 1)}: ${porque} (${t.match(re)[0]})`);
    }
  };
  anda(dist);
  return out;
}

const CADENA = 'atlas/real/xolotlcalli-cadena.json';
/** The paths of every `nota` key in a JSON value. */
export const notas = (o, p = '') => (Array.isArray(o) ? o.flatMap((v, i) => notas(v, `${p}[${i}]`))
  : o && typeof o === 'object' ? Object.entries(o).flatMap(([k, v]) => [...(k === 'nota' ? [`${p}.${k}`] : []), ...notas(v, `${p}.${k}`)]) : []);

let fallas = 0;
const ok = (cond, msg) => { console.log(`${cond ? '  ✓' : '  ✗'} ${msg}`); if (!cond) fallas++; };

// self-test: a planted dist with each kind of finding is caught; a clean one passes
const plantado = mkdtempSync(join(tmpdir(), 'interno-'));
mkdirSync(join(plantado, 'atlas/real'), { recursive: true });
writeFileSync(join(plantado, 'atlas/real/xolotlcalli-ficha.json'), JSON.stringify({ pedido: 'El fundador, por Lucia (21-oct)', cita: 'brain-hub-datos 6544ee3: context/datos/x.json, paquete 6544ee3-semilla-b6f206d' }));
writeFileSync(join(plantado, 'index.html'), '<p>los agrega Xovi Builder · AUDIT READY</p>');
const sembrados = hallazgos(plantado);
ok(sembrados.length === 5, `planted: a private path, a persona name, a replay package id and a review marker are each caught (${sembrados.length} findings)`);
writeFileSync(join(plantado, 'atlas/real/xolotlcalli-ficha.json'), JSON.stringify({ fecha: '2026-10-21', resumen: { especies: { valor: ['ambystoma_mexicanum'] } } }));
writeFileSync(join(plantado, 'index.html'), '<p>Atlas de datos abiertos</p>');
ok(hallazgos(plantado).length === 0, 'planted: a clean dist passes');
rmSync(plantado, { recursive: true, force: true });

// self-test of the byte scan: an image whose XMP carries a generator record with a local path, a PNG text chunk, a font with the booth
// database; a clean image passes
{
  const d = mkdtempSync(join(tmpdir(), 'binario-')); mkdirSync(join(d, 'species'), { recursive: true }); mkdirSync(join(d, 'fonts'), { recursive: true });
  const jpeg = (cuerpo) => Buffer.concat([Buffer.from([0xff, 0xd8, 0xff, 0xe1]), Buffer.from(cuerpo, 'latin1'), Buffer.from([0x00, 0xc4, 0x80, 0xff, 0xd9])]);
  writeFileSync(join(d, 'species/gen-plantada.jpg'), JPEG_PLANTADO());
  writeFileSync(join(d, 'species/otra.png'), Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47]), Buffer.from('tEXtSoftware\0Generated by MFLUX', 'latin1')]));
  writeFileSync(join(d, 'fonts/letra.woff2'), Buffer.concat([Buffer.from('wOF2'), Buffer.from([0, 1, 2]), Buffer.from('hub_booth5', 'latin1')]));
  writeFileSync(join(d, 'species/limpia.jpg'), jpeg('JFIF solo pixeles'));
  const h = hallazgosBinarios(d);
  ok(h.some((x) => x.startsWith('species/gen-plantada.jpg: a local home path')) && h.some((x) => x.startsWith('species/gen-plantada.jpg: a working-session folder'))
    && h.some((x) => x.startsWith('species/gen-plantada.jpg: an image generator record (model_path)')), 'planted: an image whose metadata carries a generator record with a local path is caught, by file and reason');
  ok(h.some((x) => x.startsWith('species/otra.png: an image generator record (MFLUX)')) && h.some((x) => x.startsWith('fonts/letra.woff2: the booth hub database')), 'planted: a PNG text chunk and a font are scanned too');
  ok(!h.some((x) => x.startsWith('species/limpia.jpg')), 'planted: a clean image passes');
  rmSync(d, { recursive: true, force: true });
}

ok(notas({ filas: [{ id: 'tesoreria', nota: 'Sólo movimientos en cadena' }] }).join() === '.filas[0].nota', 'planted: a «nota» key in a chain row is found');
ok(notas({ filas: [{ id: 'tesoreria', aclaracion: 'Sólo movimientos en cadena' }] }).length === 0, 'planted: the same caveat as «aclaracion» passes');

// the pilot's files must be exactly their public projection: a copy with one extra field fails, the projection itself passes
{
  const sitio = (ficha) => {
    const d = mkdtempSync(join(tmpdir(), 'copia-')); mkdirSync(join(d, 'atlas/real'), { recursive: true });
    writeFileSync(join(d, 'atlas/real/xolotlcalli-ficha.json'), JSON.stringify(ficha));
    writeFileSync(join(d, 'atlas/real/xolotlcalli-clips.json'), JSON.stringify(clipsPublicos(CLIPS)));
    writeFileSync(join(d, 'atlas/real/xolotlcalli-cadena.json'), JSON.stringify(cadenaPublica(CADENA_PRUEBA)));
    const mal = problemasDeLaCopiaPublica(d); rmSync(d, { recursive: true, force: true }); return mal;
  };
  ok(sitio(fichaPublica(FICHA)).length === 0, 'planted: the projection of each pilot file passes (and the projection is idempotent)');
  const extra = sitio({ ...fichaPublica(FICHA), pedido: 'interno' });
  ok(extra.length === 1 && extra[0].includes('xolotlcalli-ficha.json'), 'planted: a ficha with one extra field fails');
  ok(!JSON.stringify(cadenaPublica(CADENA_PRUEBA)).includes('"nota"') && cadenaPublica(CADENA_PRUEBA).filas[0].aclaracion === 'Sólo movimientos en cadena', 'the chain caveat travels as «aclaracion»');
}

const i = process.argv.indexOf('--dist');
const dist = i > 0 ? resolve(process.argv[i + 1]) : join(SITE, 'dist');
const malos = hallazgos(dist);
const copia = problemasDeLaCopiaPublica(dist);
ok(copia.length === 0, `the pilot's files are exactly their public projection${copia.length ? `:\n      ${copia.join('\n      ')}` : ''}`);
let cadena = null;
try { cadena = JSON.parse(readFileSync(join(dist, CADENA), 'utf8')); } catch {}
if (cadena) ok(notas(cadena).length === 0, `${CADENA} carries no «nota» key${notas(cadena).length ? ` (${notas(cadena).join(', ')})` : ''}`);
ok(malos.length === 0, `nothing internal in the built site${malos.length ? `:\n      ${malos.slice(0, 12).join('\n      ')}` : ''}`);
const binarios = hallazgosBinarios(dist);
ok(binarios.length === 0, `no file of the built site, read byte by byte, carries a local path, a private repository, the booth database or a generator record${binarios.length ? ` (${new Set(binarios.map((x) => x.split(':')[0])).size} file(s)):\n      ${binarios.slice(0, 8).join('\n      ')}` : ''}`);

console.log(fallas ? `\n${fallas} check(s) failed` : '\nall checks passed');
process.exit(fallas ? 1 : 0);
